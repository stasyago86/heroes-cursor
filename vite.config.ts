const PNG_SIG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

function readPngIhdrSize(absPath: string): { w: number; h: number } {
  const buf = readFileSync(absPath);
  if (buf.length < 29) return { w: 32, h: 32 };
  if (!buf.subarray(0, 8).equals(PNG_SIG)) return { w: 32, h: 32 };
  if (buf.subarray(12, 16).toString("ascii") !== "IHDR") return { w: 32, h: 32 };
  return { w: buf.readUInt32BE(16), h: buf.readUInt32BE(20) };
}

