function titleFromStem(stem: string): string {
  return stem.replace(/[_-]+/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

type CursorPackGenOptions = {
  pluginName: string;
  /** Folder under `public/` after `cursors/`, e.g. `knight` → `public/cursors/knight` */
  packFolder: string;
  outFile: string;
  idPrefix: string;
  labelPrefix: string;
  typeName: string;
  exportConst: string;
  previews: Record<string, string>;
  defaultPreview: string;
  /** Filename stem (lowercase) → popup sort key; stems omitted keep alphabetical index among PNGs. */
  orders?: Record<string, number>;
};

function generateCursorPackPlugin(opts: CursorPackGenOptions): Plugin {
  return {
    name: opts.pluginName,
    buildStart() {
      const packDir = resolve(__dirname, "public/cursors", opts.packFolder);
      const outFile = resolve(__dirname, opts.outFile);
      let files: string[] = [];
      try {
        files = readdirSync(packDir)
          .filter((f) => f.toLowerCase().endsWith(".png"))
          .sort((a, b) => a.localeCompare(b, "en"));
      } catch {
        files = [];
      }

      const lines: string[] = [
        `/** Auto-generated by Vite plugin \`${opts.pluginName}\`. Do not edit by hand. */`,
        "",
        `export type ${opts.typeName} = {`,
        "  id: string;",
        "  pathFromRoot: string;",
        "  label: string;",
        "  preview: string;",
        "  hotX: number;",
        "  hotY: number;",
        "  order: number;",
        "};",
        "",
        `export const ${opts.exportConst}: ${opts.typeName}[] = [`,
      ];

      const orders = opts.orders ?? {};
      for (let i = 0; i < files.length; i++) {
        const file = files[i];
        const abs = join(packDir, file);
        const { w, h } = readPngIhdrSize(abs);
        const stem = file.replace(/\.png$/i, "");
        const stemKey = stem.toLowerCase();
        const id = `${opts.idPrefix}-${stemKey.replace(/[^a-z0-9]+/g, "-")}`;
        const label = `${opts.labelPrefix} · ${titleFromStem(stem)}`;
        const preview = opts.previews[stemKey] ?? opts.defaultPreview;
        const order = orders[stemKey] ?? i;
        const hotX = Math.max(0, Math.min(Math.floor(w / 2), w - 1));
        const hotY = Math.max(0, Math.min(Math.floor(h * 0.1), h - 1));
        lines.push(
          `  { id: ${JSON.stringify(id)}, pathFromRoot: ${JSON.stringify(`cursors/${opts.packFolder}/${file}`)}, label: ${JSON.stringify(label)}, preview: ${JSON.stringify(preview)}, hotX: ${hotX}, hotY: ${hotY}, order: ${order} },`,
        );
      }

      lines.push("];", "");
      mkdirSync(dirname(outFile), { recursive: true });
      writeFileSync(outFile, lines.join("\n"), "utf8");
    },
  };
}

function copyManifest(): Plugin {
  return {
    name: "copy-manifest",
    closeBundle() {
      copyFileSync(resolve(__dirname, "manifest.json"), resolve(__dirname, "dist/manifest.json"));
      cpSync(resolve(__dirname, "icons"), resolve(__dirname, "dist/icons"), {
        recursive: true,
        filter: (src) => !src.endsWith(".DS_Store"),
      });
    },
  };
}

